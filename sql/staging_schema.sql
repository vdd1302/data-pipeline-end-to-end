-- Permanent, additive staging schema used by the market Data Warehouse.
-- For existing databases verify schema on a clone before initialization.
CREATE SCHEMA IF NOT EXISTS staging;
CREATE TABLE IF NOT EXISTS staging.job_observations_clean (
    raw_job_id BIGINT PRIMARY KEY,
    crawl_run_id UUID NOT NULL,
    source_job_id TEXT NOT NULL,
    snapshot_date DATE NOT NULL,
    observation_method TEXT NOT NULL,
    is_temporal_eligible BOOLEAN NOT NULL,
    job_title_clean TEXT,
    position_name TEXT,
    role_family TEXT,
    company_name_clean TEXT,
    company_size_clean TEXT,
    company_industry_clean TEXT,
    city_clean TEXT,
    district_clean TEXT,
    location_detail_clean TEXT,
    salary_min_vnd NUMERIC,
    salary_max_vnd NUMERIC,
    salary_currency TEXT,
    salary_period TEXT,
    salary_negotiable_flag BOOLEAN,
    experience_min_years NUMERIC,
    experience_max_years NUMERIC,
    experience_bucket TEXT,
    posted_date DATE,
    deadline_date DATE,
    skills_clean TEXT[],
    job_level_clean TEXT,
    job_description_clean TEXT,
    job_requirements_clean TEXT,
    benefits_clean TEXT,
    cleaning_status TEXT NOT NULL,
    quality_flags JSONB NOT NULL,
    posting_natural_key TEXT,
    canonical_job_url TEXT,
    content_hash TEXT,
    scraped_at TIMESTAMPTZ NOT NULL,
    position_classification_version TEXT,
    company_natural_key TEXT,
    company_url_clean TEXT,
    locations_clean JSONB,
    salary_midpoint_vnd NUMERIC,
    salary_disclosed_flag BOOLEAN,
    skill_normalization_version TEXT,
    skill_evidence_clean JSONB,
    cleaning_version TEXT NOT NULL,
    cleaned_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
